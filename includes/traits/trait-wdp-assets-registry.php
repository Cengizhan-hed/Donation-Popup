		// Cache within same request.
		static $asset_versions = null;
		if ( is_array( $asset_versions ) ) {
			return $asset_versions;
		}

		if ( defined( 'SCRIPT_DEBUG' ) && SCRIPT_DEBUG ) {
			$asset_versions = array(
				'css_version'       => time(),
				'js_module_version' => time(),
			);
			return $asset_versions;
		}

		$asset_cache_group = 'wdp_assets';
		// Plugin güncellemesi veya ayar kaydı ile wdp_cache_version değişince önbellek anahtarı da değişsin.
		$cache_rev = (string) WDP_ASSET_VERSION;

		// CSS version: build dosyası varsa onun mtime'ını kullan; yoksa katman dosyalarının en yükseği.
		$stack_paths    = self::get_frontend_css_stack_relative_paths();
		$built_manifest = self::get_built_css_manifest( $plugin_dir );
		$css_cache_key  = 'wdp_css_version_' . md5(
			implode( "\n", $stack_paths ) . '|' . $cache_rev . '|' . ( is_array( $built_manifest ) ? $built_manifest['file'] : 'stack' )
		);
		$css_version    = wp_cache_get( $css_cache_key, $asset_cache_group );

		if ( false === $css_version ) {
			$css_version = get_transient( $css_cache_key );
		}

		if ( false === $css_version ) {
			$max_mtime = 0;

			if ( is_array( $built_manifest ) ) {
				$built_abs = $plugin_dir . 'assets/css/' . $built_manifest['file'];
				if ( file_exists( $built_abs ) ) {
					$max_mtime = (int) filemtime( $built_abs );
				}
			} else {
				foreach ( $stack_paths as $rel ) {
					$abs = $plugin_dir . 'assets/css/' . $rel;
					if ( file_exists( $abs ) ) {
						$max_mtime = max( $max_mtime, filemtime( $abs ) );
					}
				}
			}

			$wdp_extra_css = array(
				'assets/css/src/components/phone-field.css',
			);
			foreach ( $wdp_extra_css as $extra_rel ) {
				$extra_abs = $plugin_dir . $extra_rel;
				if ( file_exists( $extra_abs ) ) {
					$max_mtime = max( $max_mtime, filemtime( $extra_abs ) );
				}
			}

			if ( $max_mtime > 0 ) {
				$css_version = $max_mtime;
			} else {
				$fallback = (string) WDP_ASSET_VERSION;
				// wdp_cache_version genelde Unix zamanı (rakam string); sürüm numarası (1.2.3) değil.
				$css_version = ctype_digit( $fallback ) ? (int) $fallback : time();
			}

			wp_cache_set( $css_cache_key, $css_version, $asset_cache_group, 300 );
			set_transient( $css_cache_key, $css_version, 300 );
		}

		// JS version: build bundle mtime when present; else highest src mtime.
		$js_stack_paths    = self::get_frontend_js_stack_relative_paths();
		$built_js_manifest = self::get_built_js_manifest( $plugin_dir );
		$js_cache_key      = 'wdp_js_version_' . md5(
			implode( "\n", $js_stack_paths ) . '|' . $cache_rev . '|' . ( is_array( $built_js_manifest ) ? $built_js_manifest['file'] : 'src' )
		);
		$js_module_version = wp_cache_get( $js_cache_key, $asset_cache_group );

		if ( false === $js_module_version ) {
			$js_module_version = get_transient( $js_cache_key );
		}

		if ( false === $js_module_version ) {
			$js_max_mtime = 0;

			if ( is_array( $built_js_manifest ) ) {
				$built_js_abs = $plugin_dir . 'assets/js/' . $built_js_manifest['file'];
				if ( file_exists( $built_js_abs ) ) {
					$js_max_mtime = (int) filemtime( $built_js_abs );
				}
			} else {
				$js_src_dir = $plugin_dir . 'assets/js/src/';
				if ( is_dir( $js_src_dir ) ) {
					$js_files = new RecursiveIteratorIterator(
						new RecursiveDirectoryIterator( $js_src_dir ),
						RecursiveIteratorIterator::SELF_FIRST
					);
					foreach ( $js_files as $file ) {
						if ( $file->isFile() && $file->getExtension() === 'js' ) {
							$js_max_mtime = max( $js_max_mtime, (int) filemtime( $file->getRealPath() ) );
						}
					}
				}
			}

			if ( $js_max_mtime > 0 ) {
				$js_module_version = $js_max_mtime;
			} else {
				$fallback          = (string) WDP_ASSET_VERSION;
				$js_module_version = ctype_digit( $fallback ) ? (int) $fallback : time();
			}

			wp_cache_set( $js_cache_key, $js_module_version, $asset_cache_group, 300 );
			set_transient( $js_cache_key, $js_module_version, 300 );
		}

		// CDN / tarayıcı: sadece dosya mtime aynı kalsa bile wdp_cache_version değişince ?ver= mutlaka değişsin.
		$asset_versions = array(
			'css_version'       => $cache_rev . '-' . (string) $css_version,
			'js_module_version' => $cache_rev . '-' . (string) $js_module_version,
		);

		return $asset_versions;
	}

	/**
	 * Enqueue assets immediately (called by force_enqueue or wp_enqueue_scripts).
	 *
	 * @return void
	 */
	public static function enqueue_assets_now() {
		// Script'ler zaten register edilmiş olmalı (enqueue_assets metodunda)
		// Sadece enqueue et

		// Script'leri register et (eğer register edilmemişse)
		if (
			! wp_script_is( 'wdp-utils-js', 'registered' )
			&& ! wp_script_is( self::FRONTEND_JS_HANDLE, 'registered' )
		) {
			// Tüm script'leri register et (enqueue_assets metodundaki gibi)
			global $post;

			// Plugin path/url
			$plugin_dir = defined( 'WDP_PLUGIN_DIR' ) ? WDP_PLUGIN_DIR : plugin_dir_path( dirname( __DIR__ ) );
			$plugin_url = defined( 'WDP_PLUGIN_URL' ) ? WDP_PLUGIN_URL : plugin_dir_url( dirname( __DIR__ ) );

			// CSS/JS versiyonlarını tek merkezli hesapla (cache-busting tutarlılığı).
			$asset_versions    = self::get_frontend_asset_versions( $plugin_dir );
			$css_version       = $asset_versions['css_version'];
			$js_module_version = $asset_versions['js_module_version'];

			// Dependencies
			$dependencies = array( 'jquery' );
			if ( wp_script_is( 'wc-add-to-cart', 'enqueued' ) ) {
				$dependencies[] = 'wc-add-to-cart';
			}

			self::register_frontend_assets( $plugin_url, $css_version, $js_module_version, $dependencies );

			// Localize script (sadece bir kez)
			if ( ! self::$frontend_data_localized ) {
				self::localize_frontend_assets( $plugin_url );
			}
		}

		if ( wp_script_is( 'wdp-form-cta-ready-js', 'registered' ) ) {
			wp_enqueue_script( 'wdp-form-cta-ready-js' );
		}
		if ( wp_script_is( self::FRONTEND_JS_HANDLE, 'registered' ) ) {
			wp_enqueue_script( self::FRONTEND_JS_HANDLE );
		} else {
			// Modular dev stack: init pulls the dependency chain.
			wp_enqueue_script( 'wdp-init-js' );
		}

		// Style'ı enqueue et
		if ( ! wp_style_is( 'wdp-donation-modal-css', 'enqueued' ) ) {
			wp_enqueue_style( 'wdp-donation-modal-css' );
		}
		// Inline style ekle
		self::maybe_enqueue_inline_style();
	}
