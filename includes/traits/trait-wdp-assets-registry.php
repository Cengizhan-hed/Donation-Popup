trait WDP_Assets_Registry_Trait {
	private static function get_frontend_css_stack_relative_paths() {
		static $paths = null;

		if ( null !== $paths ) {
			return $paths;
		}

		$config = defined( 'WDP_PLUGIN_DIR' )
			? WDP_PLUGIN_DIR . 'includes/config/frontend-css-stack.php'
			: '';

		if ( $config && file_exists( $config ) ) {
			$loaded = require $config;
			$paths  = is_array( $loaded ) ? $loaded : array();
			return $paths;
		}

		$paths = array();
		return $paths;
	}
	private static function get_frontend_js_modules() {
		static $modules = null;
		if ( null !== $modules ) {
			return $modules;
		}
		$stack_file = WDP_PLUGIN_DIR . 'includes/config/frontend-js-stack.php';
		if ( ! file_exists( $stack_file ) ) {
			$modules = array();
			return $modules;
		}
		$loaded  = require $stack_file;
		$modules = is_array( $loaded ) ? $loaded : array();
		return $modules;
	}

	private static function get_frontend_js_stack_relative_paths() {
		$paths = array();
		foreach ( self::get_frontend_js_modules() as $module ) {
			if ( is_array( $module ) && ! empty( $module['file'] ) ) {
				$paths[] = (string) $module['file'];
			} elseif ( is_string( $module ) ) {
				$paths[] = $module;
			}
		}
		return $paths;
	}

	/**
	 * Read built JS manifest generated by tools/build-js-bundle.php.
	 *
	 * @param string $plugin_dir Plugin absolute directory path.
	 * @return array|null
	 */
	private static function get_built_js_manifest( $plugin_dir ) {
		$manifest_path = $plugin_dir . 'assets/js/build/manifest.json';
		if ( ! file_exists( $manifest_path ) || ! is_readable( $manifest_path ) ) {
			return null;
		}

		$raw = file_get_contents( $manifest_path );
		if ( ! is_string( $raw ) || $raw === '' ) {
			return null;
		}

		$manifest = json_decode( $raw, true );
		if ( ! is_array( $manifest ) || empty( $manifest['file'] ) || ! is_string( $manifest['file'] ) ) {
			return null;
		}

		$rel_file = ltrim( $manifest['file'], '/' );
		$abs_file = $plugin_dir . 'assets/js/' . $rel_file;
		if ( ! file_exists( $abs_file ) ) {
			return null;
		}

		return array(
			'file' => $rel_file,
			'hash' => isset( $manifest['hash'] ) && is_string( $manifest['hash'] ) ? $manifest['hash'] : '',
		);
	}

	/**
	 * Whether to prefer the hashed JS bundle over modular src handles.
	 *
	 * @return bool
	 */
	private static function should_use_js_bundle() {
		return (bool) apply_filters( 'wdp_use_js_bundle', true );
	}

	/**
	 * CTA kuyruğu bundle’dan önce: yavaş ağda erken dokunuş sessiz yutulmasın.
	 *
	 * @param string     $plugin_url        Plugin URL.
	 * @param string|int $js_module_version Script version.
	 * @return void
	 */
	private static function register_cta_ready_script( $plugin_url, $js_module_version ) {
		if ( wp_script_is( 'wdp-form-cta-ready-js', 'registered' ) ) {
			return;
		}
		wp_register_script(
			'wdp-form-cta-ready-js',
			$plugin_url . 'assets/js/src/form/cta-ready.js',
			array(),
			$js_module_version,
			true
		);
	}
	private static function get_built_css_manifest( $plugin_dir ) {
		$manifest_path = $plugin_dir . 'assets/css/build/manifest.json';
		if ( ! file_exists( $manifest_path ) || ! is_readable( $manifest_path ) ) {
			return null;
		}

		$raw = file_get_contents( $manifest_path );
		if ( ! is_string( $raw ) || $raw === '' ) {
			return null;
		}

		$manifest = json_decode( $raw, true );
		if ( ! is_array( $manifest ) || empty( $manifest['file'] ) || ! is_string( $manifest['file'] ) ) {
			return null;
		}

		$rel_file = ltrim( $manifest['file'], '/' );
		$abs_file = $plugin_dir . 'assets/css/' . $rel_file;
		if ( ! file_exists( $abs_file ) ) {
			return null;
		}

		$critical = '';
		if ( ! empty( $manifest['critical'] ) && is_string( $manifest['critical'] ) ) {
			$critical_rel = ltrim( $manifest['critical'], '/' );
			if ( 0 === strpos( $critical_rel, 'build/critical.' ) && '.css' === substr( $critical_rel, -4 ) && false === strpos( $critical_rel, '..' ) && file_exists( $plugin_dir . 'assets/css/' . $critical_rel ) ) {
				$critical = $critical_rel;
			}
		}

		// K7: sayfa türüne göre ayrı kritik kümeler (tür => göreli dosya); geçersiz girişler atılır.
		$critical_sets = array();
		if ( ! empty( $manifest['critical_sets'] ) && is_array( $manifest['critical_sets'] ) ) {
			foreach ( $manifest['critical_sets'] as $type => $set_rel ) {
				if ( ! is_string( $type ) || ! is_string( $set_rel ) || 1 !== preg_match( '/^[a-z0-9-]+$/', $type ) ) {
					continue;
				}
				$set_rel = ltrim( $set_rel, '/' );
				if ( 0 === strpos( $set_rel, 'build/critical.' ) && '.css' === substr( $set_rel, -4 ) && false === strpos( $set_rel, '..' ) && file_exists( $plugin_dir . 'assets/css/' . $set_rel ) ) {
					$critical_sets[ $type ] = $set_rel;
				}
			}
		}

		return array(
			'file'          => $rel_file,
			'hash'          => isset( $manifest['hash'] ) && is_string( $manifest['hash'] ) ? $manifest['hash'] : '',
			'critical'      => $critical,
			'critical_sets' => $critical_sets,
		);
	}

	/**
	 * K3/K7: ilk görünüm kritik CSS'i (derleme çıktısı; tam paketin alt kümesi). Yoksa boş (bölme yapılmaz).
	 *
	 * `$type` sayfa türüdür (örn. `product-fixed`, `shop`); o tür için ayrı küme yoksa ya da tür boşsa tüm türlerin birleşimi
	 * (güvenli varsayılan) döner.
	 *
	 * @param string $type Sayfa türü ('' = birleşim).
	 * @return string
	 */
	public static function get_critical_bundle_css( $type = '' ) {
		static $cache = array();
		$type = is_string( $type ) ? $type : '';
		if ( isset( $cache[ $type ] ) ) {
			return $cache[ $type ];
		}
		$cache[ $type ] = '';
		$plugin_dir     = defined( 'WDP_PLUGIN_DIR' ) ? WDP_PLUGIN_DIR : plugin_dir_path( dirname( __DIR__ ) );
		$manifest       = self::get_built_css_manifest( $plugin_dir );
		if ( ! is_array( $manifest ) ) {
			return '';
		}
		$rel = '';
		if ( '' !== $type && isset( $manifest['critical_sets'][ $type ] ) ) {
			$rel = (string) $manifest['critical_sets'][ $type ];
		} elseif ( ! empty( $manifest['critical'] ) ) {
			$rel = (string) $manifest['critical'];
		}
		if ( '' !== $rel ) {
			$raw = file_get_contents( $plugin_dir . 'assets/css/' . $rel ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- yerel eklenti dosyası.
			if ( is_string( $raw ) ) {
				// Bir <style> bloğunu erken kapatamasın.
				$cache[ $type ] = trim( str_ireplace( '</style', '<\/style', $raw ) );
			}
		}
		return $cache[ $type ];
	}

	private static function maybe_refresh_asset_revision_from_files( $plugin_dir ) {
		static $checked = false;
		if ( $checked ) {
			return;
		}
		$checked = true;

		$stack_paths     = self::get_frontend_css_stack_relative_paths();
		$signature_parts = array();

		foreach ( $stack_paths as $rel ) {
			$abs = $plugin_dir . 'assets/css/' . $rel;
			if ( ! file_exists( $abs ) ) {
				continue;
			}
			$mtime             = filemtime( $abs );
			$size              = filesize( $abs );
			$signature_parts[] = $rel . ':' . (string) $mtime . ':' . (string) $size;
		}

		if ( empty( $signature_parts ) ) {
			return;
		}

		$current_signature = md5( implode( '|', $signature_parts ) );
		$stored_signature  = get_option( 'wdp_css_signature', '' );

		if ( ! is_string( $stored_signature ) || $stored_signature !== $current_signature ) {
			update_option( 'wdp_css_signature', $current_signature, false );
			update_option( 'wdp_cache_version', time() );
			self::purge_known_page_caches();
		}
	}
	private static function register_frontend_assets( $plugin_url, $css_version, $js_module_version, $dependencies ) {
		if ( self::$frontend_assets_registered ) {
			return;
		}

		$plugin_dir = defined( 'WDP_PLUGIN_DIR' ) ? WDP_PLUGIN_DIR : plugin_dir_path( dirname( __DIR__ ) );

		if ( self::should_use_js_bundle() ) {
			$built_js = self::get_built_js_manifest( $plugin_dir );
			if ( is_array( $built_js ) && ! empty( $built_js['file'] ) ) {
				self::register_cta_ready_script( $plugin_url, $js_module_version );
				$bundle_deps   = is_array( $dependencies ) ? $dependencies : array( 'jquery' );
				$bundle_deps[] = 'wdp-form-cta-ready-js';
				// E8W: telefon ülke listesi + çeviri sözlüğü sayfa HTML'ine gömülmez; paketten önce çalışan ayrı betik.
				if ( class_exists( 'WDP_Client_Data' ) && WDP_Client_Data::is_enabled() ) {
					wp_register_script( WDP_Client_Data::HANDLE, WDP_Client_Data::url(), array( 'wdp-form-cta-ready-js' ), null, true ); // phpcs:ignore WordPress.WP.EnqueuedResourceParameters.MissingVersion -- sürüm adresin içinde (ver=).
					$bundle_deps[] = WDP_Client_Data::HANDLE;
				}
				wp_register_script(
					self::FRONTEND_JS_HANDLE,
					$plugin_url . 'assets/js/' . $built_js['file'],
					$bundle_deps,
					$js_module_version,
					true
				);
				self::register_frontend_style_stack( $plugin_url, $css_version );
				self::$frontend_assets_registered = true;
				return;
			}
		}

		$base_deps = is_array( $dependencies ) ? $dependencies : array( 'jquery' );

		foreach ( self::get_frontend_js_modules() as $module ) {
			if ( ! is_array( $module ) || empty( $module['handle'] ) || empty( $module['file'] ) ) {
				continue;
			}

			$handle = (string) $module['handle'];
			$file   = (string) $module['file'];
			$deps   = isset( $module['deps'] ) && is_array( $module['deps'] ) ? $module['deps'] : array();

			if ( 'wdp-utils-js' === $handle ) {
				$deps = array_merge( $deps, $base_deps );
			}

			wp_register_script(
				$handle,
				$plugin_url . 'assets/js/' . ltrim( $file, '/' ),
				$deps,
				$js_module_version,
				true
			);
		}

		self::register_frontend_style_stack( $plugin_url, $css_version );
		self::$frontend_assets_registered = true;
	}

	/**
	 * Ön yüz stillerini tek tek register et (@import yerine — her dosyaya aynı ?ver= gider).
	 *
	 * @param string     $plugin_url  Plugin URL.
	 * @param string|int $css_version Style version.
	 * @return void
	 */
	private static function register_frontend_style_stack( $plugin_url, $css_version ) {
		$plugin_dir = defined( 'WDP_PLUGIN_DIR' ) ? WDP_PLUGIN_DIR : plugin_dir_path( dirname( __DIR__ ) );

		$built_manifest = self::get_built_css_manifest( $plugin_dir );
		if ( is_array( $built_manifest ) && ! empty( $built_manifest['file'] ) ) {
			$rel_file = ltrim( (string) $built_manifest['file'], '/' );
			$abs_file = $plugin_dir . 'assets/css/' . $rel_file;
			if ( file_exists( $abs_file ) ) {
				wp_register_style(
					self::FRONTEND_CSS_HANDLE,
					$plugin_url . 'assets/css/' . $rel_file,
					array(),
					$css_version
				);
				return;
			}
		}

		// Geliştirme yedeği: bundle yoksa katman katman (aynı stack listesi).
		$stack    = self::get_frontend_css_stack_relative_paths();
		$existing = array();
		foreach ( $stack as $rel ) {
			$abs = $plugin_dir . 'assets/css/' . $rel;
			if ( file_exists( $abs ) ) {
				$existing[] = $rel;
			}
		}

		if ( empty( $existing ) ) {
			wp_register_style(
				self::FRONTEND_CSS_HANDLE,
				$plugin_url . 'assets/css/donation-modal.css',
				array(),
				$css_version
			);
			return;
		}

		$deps = array();
		$last = count( $existing ) - 1;
		foreach ( $existing as $i => $rel ) {
			$handle     = ( $i === $last ) ? self::FRONTEND_CSS_HANDLE : 'wdp-css-layer-' . $i;
			$layer_deps = ( $i === 0 ) ? array() : $deps;
			wp_register_style( $handle, $plugin_url . 'assets/css/' . $rel, $layer_deps, $css_version );
			$deps = array( $handle );
		}
	}

	/**
	 * İstemci para birimi/dil bağlamı.
	 *
	 * @param string $currency_code Mağaza para birimi.
	 * @return array<string, mixed>
	 */
	private static function client_context( $currency_code ) {
		$locale  = function_exists( 'determine_locale' ) ? (string) determine_locale() : (string) get_locale();
		$context = array(
			'currency'           => strtoupper( $currency_code ),
			'lang'               => strtolower( (string) preg_split( '/[-_]/', $locale )[0] ),
			'currency_cookies'   => array(),
			'lang_cookies'       => array(),
			'switcher_selectors' => array( '[data-currency]', "a[href*='currency=']" ),
			'change_events'      => array(),
		);
		/**
		 * Ön yüz para birimi/dil sinyali (çerez adları, değiştirici seçicileri, olay adları).
		 * Çekirdek hiçbir eklenti/çerez adı bilmez; çoklu para birimi/dil kullanan siteler site koduyla ekler (docs/site-snippets/).
		 *
		 * @param array<string, mixed> $context Bağlam.
		 */
		$filtered = apply_filters( 'wdp_client_context', $context );
		// @phpstan-ignore function.alreadyNarrowedType (filter callbacks may return anything)
		return is_array( $filtered ) ? $filtered : $context;
	}

